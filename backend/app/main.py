def compare_ab_test_study(user_id: str, study_id: str) -> dict:



    u_key = normalize_user_id(user_id)



    with _AB_LOCK:



        store = _load_ab_store()



        user_studies = store.get(u_key, [])



        target = next((s for s in user_studies if s.get("study_id") == study_id), None)



        if not target:



            raise ValueError(f"Study {study_id} not found for user {u_key}")



    ranked = []



    for v in target.get("variants", []):



        m = v.get("metrics", {})



        views = max(0, int(m.get("views", 0)))



        retention = max(0.0, float(m.get("retention_pct", 0.0)))



        shares = max(0, int(m.get("shares", 0)))



        likes = max(0, int(m.get("likes", 0)))



        comments = max(0, int(m.get("comments", 0)))



        engagement_rate_pct = ((likes + shares * 2 + comments * 2) / views * 100.0) if views > 0 else 0.0



        score = round(retention * 0.65 + min(engagement_rate_pct * 4.0, 35.0), 2)



        ranked.append({



            "variant_id": v.get("variant_id"),



            "label": v.get("label"),



            "hook": v.get("hook"),



            "opening_style": v.get("opening_style"),



            "caption_style": v.get("caption_style"),



            "metrics": m,



            "engagement_rate_pct": round(engagement_rate_pct, 2),



            "performance_score": score,



        })



    ranked.sort(key=lambda item: item["performance_score"], reverse=True)



    has_data = any(item["metrics"].get("views", 0) > 0 or item["metrics"].get("retention_pct", 0.0) > 0 for item in ranked)



    leader = ranked[0] if (ranked and has_data) else None



    return {"study_id": study_id, "user_id": u_key, "clip_id": target.get("clip_id"), "leader_variant_id": leader["variant_id"] if leader else None, "ranked_variants": ranked, "virality_note": _VIRALITY_DISCLAIMER}











def coach_creator_performance(



    clips: list[dict],



    user_id: str = "default",



    apply_to_clip_dna: bool = False,



) -> dict:



    u_key = normalize_user_id(user_id)



    rows = [c for c in (clips or []) if isinstance(c, dict)]



    if not rows:



        return {



            "user_id": u_key,



            "clips_analyzed": 0,



            "averages": {"views": 0, "retention_pct": 0.0, "share_rate_pct": 0.0, "engagement_rate_pct": 0.0},



            "recommendations": [{"area": "baseline", "priority": "medium", "action": "Publish at least 3 clips and log views, retention %, and shares to unlock personalized coaching."}],



            "dna_updated": False,



        }



    total_views = 0



    retention_sum = 0.0



    share_rate_sum = 0.0



    engagement_rate_sum = 0.0



    long_clip_count = 0



    high_retention_count = 0



    for c in rows:



        views = max(0, int(c.get("views", 0) or 0))



        retention = max(0.0, min(100.0, float(c.get("retention_pct", 0.0) or 0.0)))



        likes = max(0, int(c.get("likes", 0) or 0))



        shares = max(0, int(c.get("shares", 0) or 0))



        comments = max(0, int(c.get("comments", 0) or 0))



        dur = max(0.0, float(c.get("duration_sec", 0.0) or 0.0))



        total_views += views



        retention_sum += retention



        if dur > 45.0:



            long_clip_count += 1



        if retention >= 72.0:



            high_retention_count += 1



        if views > 0:



            share_rate_sum += (shares / views) * 100.0



            engagement_rate_sum += ((likes + shares * 2 + comments * 2) / views) * 100.0



    n = len(rows)



    avg_views = round(total_views / n, 1)



    avg_retention = round(retention_sum / n, 2)



    avg_share_rate = round(share_rate_sum / n, 2)



    avg_engagement_rate = round(engagement_rate_sum / n, 2)



    recommendations: list[dict] = []



    suggested_dna_updates: dict = {}



    if avg_retention < 55.0:



        recommendations.append({"area": "opening_hook_and_pacing", "priority": "high", "action": "Cut the first 1-2 seconds of setup, trim pauses above 0.6s with Dead-Air Remover, and test 2-3 hook variants in Viral A/B Testing Studio."})



        suggested_dna_updates["zoom_intensity"] = "dynamic"



    elif avg_retention < 70.0:



        recommendations.append({"area": "mid_clip_momentum", "priority": "medium", "action": "Keep punchy zooms and highlight caption emphasis active through the middle of the clip so viewers stay until the payoff."})



        suggested_dna_updates["zoom_intensity"] = "punchy"



    if avg_share_rate < 1.5:



        recommendations.append({"area": "shareability_and_series", "priority": "medium", "action": "Lead with a sharper curiosity gap or contrarian claim, and group related clips into numbered episodes with Auto-Series Creator."})



    if long_clip_count > n / 2.0 and avg_retention < 65.0:



        recommendations.append({"area": "clip_length", "priority": "medium", "action": "Aim for tighter 20-35 second cuts instead of longer clips when retention dips past the halfway mark."})



    if high_retention_count > 0:



        recommendations.append({"area": "winning_pattern", "priority": "low", "action": f"{high_retention_count} of {n} clips hit 72%+ retention ? keep those hook structures and caption styles as your baseline."})



    if not recommendations:



        recommendations.append({"area": "consistency", "priority": "low", "action": "Retention and engagement look healthy ? keep your current pacing consistent and test subtle caption or title variations."})



    dna_updated = False



    if apply_to_clip_dna and suggested_dna_updates:



        save_clip_dna(u_key, suggested_dna_updates)



        dna_updated = True



    return {



        "user_id": u_key,



        "clips_analyzed": n,



        "averages": {"views": avg_views, "retention_pct": avg_retention, "share_rate_pct": avg_share_rate, "engagement_rate_pct": avg_engagement_rate},



        "suggested_dna_updates": suggested_dna_updates,



        "dna_updated": dna_updated,



        "recommendations": recommendations,



    }



def prepare_render_with_dna_collision_and_quota(

    user_id: str | None = None,

    clip_id: str = "clip_1",

    source_id: str = "",

    start_sec: float = 0.0,

    end_sec: float = 0.0,

    hook: str = "",

    graphics_preset: str | None = None,

    normalize_lufs: bool = True,

    is_pro: bool = False,

    allow_collision: bool = False,

    consume_quota: bool = True,

) -> dict:

    """Runs Clip DNA resolution, collision check, and quota consumption in safe order."""

    u_key = normalize_user_id(user_id) if "normalize_user_id" in globals() else ((user_id or "guest").strip().lower() or "guest")

    space = get_user_personal_space(u_key, is_pro=is_pro) if "get_user_personal_space" in globals() else {"recent_clips": []}

    dna_opts = (

        apply_clip_dna_to_render_opts(u_key, graphics_preset=graphics_preset, normalize_lufs=normalize_lufs)

        if "apply_clip_dna_to_render_opts" in globals()

        else {"graphics_preset": (graphics_preset or "760"), "normalize_lufs": bool(normalize_lufs)}

    )



    candidate = {

        "clip_id": clip_id,

        "source_id": source_id,

        "start_sec": float(start_sec or 0.0),

        "end_sec": float(end_sec or 0.0),

        "hook": hook or "",

    }

    existing_clips = space.get("recent_clips") if isinstance(space, dict) else []

    collision = (

        detect_clip_collisions(candidate, existing_clips if isinstance(existing_clips, list) else [])

        if "detect_clip_collisions" in globals()

        else {"has_collision": False, "highest_severity": "none", "collisions": []}

    )



    if collision.get("has_collision") and collision.get("highest_severity") == "high" and not allow_collision:

        return {

            "allowed": False,

            "reason": "clip_collision_detected",

            "user_id": u_key,

            "dna_opts": dna_opts,

            "collision": collision,

        }



    quota_result = None

    if consume_quota and not is_pro and "consume_free_clip_quota" in globals():

        quota_result = consume_free_clip_quota(u_key)

        if isinstance(quota_result, dict) and quota_result.get("allowed") is False:

            return {

                "allowed": False,

                "reason": "free_clip_quota_exceeded",

                "user_id": u_key,

                "dna_opts": dna_opts,

                "collision": collision,

                "quota": quota_result,

            }



    return {

        "allowed": True,

        "user_id": u_key,

        "dna_opts": dna_opts,

        "collision": collision,

        "quota": quota_result,

    }


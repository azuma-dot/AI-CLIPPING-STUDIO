def build_auto_series(



    moments: list[dict],



    series_title: str = "Highlight Series",



    max_episodes: int = 10,



    title_style: str = "part",



) -> dict:



    valid_moments = [m for m in (moments or []) if isinstance(m, dict)]



    if not valid_moments:



        return {"series_id": f"series_{_cos_uuid.uuid4().hex[:8]}", "series_title": series_title or "Highlight Series", "episode_count": 0, "episodes": []}



    token_sets = [_as_extract_tokens(m) for m in valid_moments]



    scored: list[tuple[float, float, int, dict]] = []



    for idx, m in enumerate(valid_moments):



        my_tokens = token_sets[idx]



        overlap_score = 0.0



        for jdx, other_tokens in enumerate(token_sets):



            if idx == jdx or not my_tokens or not other_tokens:



                continue



            union = len(my_tokens | other_tokens)



            if union > 0:



                overlap_score += len(my_tokens & other_tokens) / union



        start_sec = float(m.get("start_sec", m.get("start", idx * 10.0)) or 0.0)



        scored.append((overlap_score, start_sec, idx, m))



    cap = max(1, min(50, int(max_episodes or 10)))



    top_by_relevance = sorted(scored, key=lambda item: (-item[0], item[1], item[2]))[:cap]



    ordered = sorted(top_by_relevance, key=lambda item: (item[1], item[2]))



    total_eps = len(ordered)



    episodes: list[dict] = []



    for ep_idx, (_rel, _start, orig_idx, m) in enumerate(ordered, start=1):



        raw_id = str(m.get("clip_id") or m.get("id") or f"moment_{orig_idx + 1}")



        raw_hook = str(m.get("hook") or m.get("title") or m.get("topic") or f"Moment {ep_idx}").strip()



        s_sec = float(m.get("start_sec", m.get("start", 0.0)) or 0.0)



        e_sec = float(m.get("end_sec", m.get("end", s_sec)) or s_sec)



        episodes.append({



            "episode_number": ep_idx,



            "total_episodes": total_eps,



            "clip_id": raw_id,



            "start_sec": round(s_sec, 3),



            "end_sec": round(e_sec, 3),



            "hook": raw_hook,



            "episode_title": format_series_episode_title(series_title, ep_idx, raw_hook, title_style),



        })



    return {"series_id": f"series_{_cos_uuid.uuid4().hex[:8]}", "series_title": " ".join((series_title or "Highlight Series").split()).strip(), "episode_count": total_eps, "episodes": episodes}












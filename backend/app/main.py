def build_smart_916_crop_filter(











































    src_width: int,











































    src_height: int,











































    focus_x: str | float = "center",











































) -> str:











































    """Returns a fast FFmpeg crop filter string for 9:16 vertical framing with horizontal focus."""











































    w = max(2, int(src_width))











































    h = max(2, int(src_height))























































































    # Target 9:16 crop box inside source dimensions











































    target_w = min(w, int(round(h * 9 / 16)))











































    target_h = min(h, int(round(target_w * 16 / 9)))











































    target_w -= target_w % 2











































    target_h -= target_h % 2











































    target_w = max(2, target_w)











































    target_h = max(2, target_h)























































































    max_x = max(0, w - target_w)











































    if isinstance(focus_x, (int, float)):











































        ratio = max(0.0, min(1.0, float(focus_x)))











































    else:











































        token = str(focus_x).strip().lower()











































        ratio = {"left": 0.25, "right": 0.75, "center": 0.5}.get(token, 0.5)























































































    x_pos = int(round(max_x * ratio))











































    x_pos -= x_pos % 2











































    x_pos = max(0, min(max_x, x_pos))























































































    y_pos = max(0, (h - target_h) // 2)











































    y_pos -= y_pos % 2























































































    return f"crop={target_w}:{target_h}:{x_pos}:{y_pos}"



































































































































